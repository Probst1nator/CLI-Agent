"""Bug report tool for reporting unexpected tool behavior."""

import os
import re
from datetime import datetime
from pathlib import Path

from shared.utils.tool_logging import get_logger_for_tool_module

logger = get_logger_for_tool_module(__name__)


class bug_report:
    """Tool for reporting bugs when other tools don't behave as expected."""

    @staticmethod
    def get_delim() -> str:
        """Return the tool's delimiter/name."""
        return "bug_report"

    @staticmethod
    def get_tool_info() -> dict:
        """Return tool metadata for the LLM."""
        return {
            "name": "bug_report",
            "description": (
                "Report a bug when a tool does not behave as expected. "
                "Use this to document unexpected behavior, errors, or inconsistencies "
                "in tool outputs. The report will be appended to BUG_REPORTS.md for review."
            ),
            "example": (
                "<bug_report>"
                "<title>search_web returns empty results for valid queries</title>"
                "<report>When querying 'Python documentation' with search_web, "
                "the tool returns an empty result set despite the query being valid. "
                "Expected: List of search results. Actual: Empty array.</report>"
                "</bug_report>"
            ),
        }

    @staticmethod
    def run(content: str) -> str:
        """
        Parse bug report content and append to BUG_REPORTS.md.

        Args:
            content: XML-formatted string containing <title> and <report> tags

        Returns:
            Success or error message
        """
        try:
            # Parse title
            title_match = re.search(r"<title>(.*?)</title>", content, re.DOTALL)
            if not title_match:
                logger.error("No <title> tag found in bug_report content")
                return "Error: Missing <title> tag in bug report"

            title = title_match.group(1).strip()

            # Parse report
            report_match = re.search(r"<report>(.*?)</report>", content, re.DOTALL)
            if not report_match:
                logger.error("No <report> tag found in bug_report content")
                return "Error: Missing <report> tag in bug report"

            report = report_match.group(1).strip()

            # Validate inputs
            if not title:
                return "Error: Title cannot be empty"
            if not report:
                return "Error: Report cannot be empty"

            # Get the project root (where BUG_REPORTS.md should be)
            bug_reports_path = Path.cwd() / "BUG_REPORTS.md"

            # Format the bug report entry
            timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            entry = f"\n## {title}\n\n**Reported:** {timestamp}\n\n{report}\n\n---\n"

            # Create file with header if it doesn't exist
            if not bug_reports_path.exists():
                logger.info(f"Creating new bug reports file at {bug_reports_path}")
                header = "# Bug Reports\n\nThis file contains bug reports generated by the agent when tools don't behave as expected.\n\n---\n"
                bug_reports_path.write_text(header)

            # Append the bug report
            with open(bug_reports_path, "a", encoding="utf-8") as f:
                f.write(entry)

            logger.info(f"Bug report added: {title}")
            return f"Bug report successfully added to {bug_reports_path}\nTitle: {title}"

        except Exception as e:
            logger.error(f"Failed to create bug report: {e}", exc_info=True)
            return f"Error creating bug report: {str(e)}"
